                "Side",
                "02 Presentation",
                "Branch-name side",
                "Above",
                "Above matches the requested plan presentation. Below and alternating remain available where drawing congestion requires them.",
                new[]
                {
                    "Above",
                    "Below",
                    "Alternating"
                });
