                new List<NetworkAlignmentPlan>();
            try
            {
                using (Transaction read =
                    database.TransactionManager.StartTransaction())
                {
                    foreach (ObjectId networkId in
                        networkIds
                            .Distinct()
                            .OrderBy(id =>
                                id.Handle.Value))
                    {
                        plans.Add(
                            BuildNetworkPlan(
                                networkId,
                                read));
