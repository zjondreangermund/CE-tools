        [CommandMethod(
            "CE_TOOLS",
            "CE_SEWALIGN",
            CommandFlags.Modal | CommandFlags.Redraw | CommandFlags.UsePickSet)]
        public void CreateBranchAlignments()
        {
            Document document = AcApplication.DocumentManager.MdiActiveDocument;
            if (document == null)
            {
                return;
            }

            Editor editor = document.Editor;
            Database database = document.Database;
            CivilDocument civilDocument = CivilApplication.ActiveDocument;
            if (civilDocument == null)
            {
                editor.WriteMessage(
                    "\nCE_SEWALIGN cancelled. No active Civil 3D document is available.");
                return;
            }

            List<ObjectId> networkIds;
            int unsupported = 0;
            var scope = new PromptKeywordOptions(
                "\nSewer alignment scope [AllNetworkParts/Select] <AllNetworkParts>: ")
            {
                AllowNone = true
            };
            scope.Keywords.Add("AllNetworkParts");
            scope.Keywords.Add("Select");
            PromptResult scopeResult = editor.GetKeywords(scope);
            if (scopeResult.Status == PromptStatus.Cancel)
                return;

            bool selectManually =
                scopeResult.Status == PromptStatus.OK &&
                string.Equals(
                    scopeResult.StringResult,
                    "Select",
                    StringComparison.OrdinalIgnoreCase);

            try
            {
                if (selectManually)
                {
                    PromptSelectionResult selection =
                        editor.SelectImplied();
                    if (selection.Status != PromptStatus.OK ||
                        selection.Value == null ||
                        selection.Value.Count == 0)
                    {
                        selection = editor.GetSelection(
                            new PromptSelectionOptions
                            {
                                MessageForAdding =
                                    "\nSelect one or more CE-sequenced sewer pipes or structures: ",
                                AllowDuplicates = false,
                                RejectObjectsFromNonCurrentSpace = true
                            });
                    }

                    if (selection.Status != PromptStatus.OK ||
                        selection.Value == null ||
                        selection.Value.Count == 0)
                        return;

                    ReadSelectedNetworks(
                        database,
                        selection.Value.GetObjectIds(),
                        out networkIds,
                        out unsupported);
                }
                else
                {
                    networkIds = ReadAllSequencedSewerNetworks(
                        database,
                        civilDocument);
                }
            }
            catch (System.Exception exception)
            {
                editor.WriteMessage(
                    "\nCE_SEWALIGN cancelled while reading the selection: " +
                    exception.Message);
                return;
            }

            if (networkIds.Count == 0)
            {
                editor.WriteMessage(
                    "\nCE_SEWALIGN: select at least one Civil 3D gravity-network pipe or structure.");
                return;
            }

            List<NetworkAlignmentPlan> plans;
            try
            {
                using (Transaction transaction =
                    database.TransactionManager.StartTransaction())
                {
                    plans = networkIds
                        .OrderBy(id => id.Handle.Value)
                        .Select(id => BuildNetworkPlan(id, transaction))
                        .ToList();
                }
            }
            catch (System.Exception exception)
            {
                editor.WriteMessage("\nCE_SEWALIGN cancelled. " + exception.Message);
                return;
            }

            int branchCount = plans.Sum(plan => plan.Branches.Count);
            editor.WriteMessage(
                "\nCE_SEWALIGN preview: networks={0}; branches={1}; unsupported selections ignored={2}.",
                plans.Count,
                branchCount,
                unsupported);

            foreach (NetworkAlignmentPlan plan in plans)
            {
                editor.WriteMessage("\n  Network: {0}", plan.NetworkName);
                foreach (BranchAlignmentPlan branch in plan.Branches)
                {
                    editor.WriteMessage(
                        "\n    {0}: pipes={1}; structures={2}; sampled vertices={3}; start structure={4} -> station 0+000",
                        branch.BranchName,
                        branch.PipeIds.Count,
                        branch.StructureIds.Count,
                        branch.PlanPoints.Count,
                        branch.StartStructureName);
                }
            }

            if (!Confirm(
                    editor,
                    "Create or refresh the sewer branch alignments and plan labels"))
            {
                editor.WriteMessage(
                    "\nCE_SEWALIGN cancelled. No alignments or labels were changed.");
                return;
            }

            try
            {
                int alignmentsCreated;
                int labelsCreated;
                CreateAlignmentsAndLabels(
                    database,
                    civilDocument,
                    plans,
                    out alignmentsCreated,
                    out labelsCreated);

                editor.WriteMessage(
                    "\nCE_SEWALIGN complete. Alignments created/refreshed: {0}; branch-name labels placed: {1}. Every branch is oriented from its resolved P#.1 start structure and verified at station 0+000.",
                    alignmentsCreated,
                    labelsCreated);
            }
            catch (System.Exception exception)
            {
                editor.WriteMessage(
                    "\nCE_SEWALIGN cancelled. The transaction was not committed: " +
                    exception.Message);
            }
        }

        [CommandMethod(
            "CE_TOOLS",
            "CE_SEWALIGNSTARTFIX",
            CommandFlags.Modal | CommandFlags.Redraw | CommandFlags.UsePickSet)]
        public void RepairExistingAlignmentStarts()
        {
            Document document = AcApplication.DocumentManager.MdiActiveDocument;
            CivilDocument civilDocument = CivilApplication.ActiveDocument;
            if (document == null || civilDocument == null)
                return;

            Editor editor = document.Editor;
            List<ObjectId> networkIds;
            int unsupported = 0;

            var scope = new PromptKeywordOptions(
                "\nSewer alignment start repair scope [AllNetworkParts/Select] <AllNetworkParts>: ")
            {
                AllowNone = true
            };
            scope.Keywords.Add("AllNetworkParts");
            scope.Keywords.Add("Select");
            PromptResult scopeResult = editor.GetKeywords(scope);
            if (scopeResult.Status == PromptStatus.Cancel)
                return;

            bool selectManually =
                scopeResult.Status == PromptStatus.OK &&
                string.Equals(
                    scopeResult.StringResult,
                    "Select",
                    StringComparison.OrdinalIgnoreCase);

            try
            {
                if (selectManually)
                {
                    PromptSelectionResult selection = editor.SelectImplied();
                    if (selection.Status != PromptStatus.OK ||
                        selection.Value == null ||
                        selection.Value.Count == 0)
                    {
                        selection = editor.GetSelection(
                            new PromptSelectionOptions
                            {
                                MessageForAdding =
                                    "\nSelect sewer pipes/structures whose branch alignments must start at the branch-start structure: ",
                                AllowDuplicates = false,
                                RejectObjectsFromNonCurrentSpace = true
                            });
                    }

                    if (selection.Status != PromptStatus.OK ||
                        selection.Value == null ||
                        selection.Value.Count == 0)
                        return;

                    ReadSelectedNetworks(
                        document.Database,
                        selection.Value.GetObjectIds(),
                        out networkIds,
                        out unsupported);
                }
                else
                {
                    networkIds = ReadAllSequencedSewerNetworks(
                        document.Database,
                        civilDocument);
                }
            }
            catch (System.Exception exception)
            {
                editor.WriteMessage(
                    "\nCE_SEWALIGNSTARTFIX cancelled while resolving sewer networks. " +
                    exception.Message);
                return;
            }

            if (networkIds.Count == 0)
            {
                editor.WriteMessage(
                    "\nCE_SEWALIGNSTARTFIX: no CE-sequenced sewer networks were found.");
                return;
            }

            List<NetworkAlignmentPlan> plans;
            using (Transaction read =
                document.Database.TransactionManager.StartTransaction())
            {
                plans = networkIds
                    .OrderBy(id => id.Handle.Value)
                    .Select(id => BuildNetworkPlan(id, read))
                    .ToList();
            }

            int checkedAlignments = 0;
            int reversedAlignments = 0;
            int missingAlignments = 0;
            var repaired = new List<string>();

            try
            {
                using (DocumentLock documentLock = document.LockDocument())
                using (Transaction transaction =
                    document.Database.TransactionManager.StartTransaction())
                {
                    foreach (NetworkAlignmentPlan plan in plans)
                    {
                        foreach (BranchAlignmentPlan branch in plan.Branches)
                        {
                            ObjectId alignmentId =
                                ResolveExistingBranchAlignmentId(
                                    civilDocument,
                                    plan,
                                    branch,
                                    transaction);
                            if (alignmentId.IsNull)
                            {
                                missingAlignments++;
                                continue;
                            }

                            CivilAlignment alignment = transaction.GetObject(
                                alignmentId,
                                OpenMode.ForWrite,
                                false) as CivilAlignment;
                            if (alignment == null)
                            {
                                missingAlignments++;
                                continue;
                            }

                            Point2d expected = new Point2d(
                                branch.PlanPoints[0].X,
                                branch.PlanPoints[0].Y);
                            bool reverseNeeded =
                                PlanDistance(
                                    ReadAlignmentStartPoint(alignment),
                                    expected) >
                                PlanDistance(
                                    ReadAlignmentEndPoint(alignment),
                                    expected) + 0.001;

                            EnsureAlignmentDirectionAtBranchStart(
                                alignment,
                                branch.BranchName,
                                branch.StartStructureName,
                                branch.PlanPoints[0]);
                            ForceAlignmentStartStationZero(
                                alignment,
                                branch.BranchName,
                                branch.StartStructureName,
                                branch.PlanPoints[0]);

                            checkedAlignments++;
                            if (reverseNeeded)
                                reversedAlignments++;
                            repaired.Add(
                                branch.BranchName +
                                " -> " +
                                branch.StartStructureName +
                                " = 0+000");
                        }
                    }

                    transaction.Commit();
                }
            }
            catch (System.Exception exception)
            {
                editor.WriteMessage(
                    "\nCE_SEWALIGNSTARTFIX cancelled; no repair transaction was committed. " +
                    exception.Message);
                return;
            }

            document.Editor.Regen();
            editor.WriteMessage(
                "\nCE_SEWALIGNSTARTFIX complete. Alignments verified/repaired={0}; reversed={1}; missing/unresolved={2}; unsupported selections ignored={3}.",
                checkedAlignments,
                reversedAlignments,
                missingAlignments,
                unsupported);
            foreach (string item in repaired.Take(20))
                editor.WriteMessage("\n  " + item);
            if (repaired.Count > 20)
                editor.WriteMessage(
                    "\n  ... plus {0} additional branch alignments.",
                    repaired.Count - 20);
        }

        [CommandMethod(
            "CE_TOOLS",
            "CE_SEWBRANCHNAMES",
            CommandFlags.Modal | CommandFlags.Redraw | CommandFlags.UsePickSet)]
        public void RefreshBranchNames()
        {
            Document document =
                AcApplication.DocumentManager.MdiActiveDocument;
            CivilDocument civilDocument =
                CivilApplication.ActiveDocument;
            if (document == null ||
                civilDocument == null)
                return;

            Editor editor = document.Editor;
            Database database = document.Database;
            SewerProductionSettings productionSettings =
                SewerProductionSettings.Read(database);

            var model =
                new ProductionSettingsDialogModel(
                    "CE Tools - Sewer Branch Names",
                    "Add or refresh green Branch-x names like the plan example: centred on each straight sewer branch section, rotated with the pipe run and offset clear above the sewer annotation.");

            model.AddChoice(
                "Scope",
                "01 Branches",
                "Branches to label",
                "All sewer branches",
                "Label every CE-sequenced sewer branch, or only branches from multiple selected sewer pipes/structures.",
                new[]
                {
                    "All sewer branches",
                    "Selected sewer parts"
