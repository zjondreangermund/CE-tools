            branchLayerChoices.Insert(0, createLayerChoice);
            string branchLayerDefault = branchLayerChoices.Any(name =>
                    string.Equals(
                        name,
                        productionSettings.BranchLabelLayer,
                        StringComparison.OrdinalIgnoreCase))
                ? productionSettings.BranchLabelLayer
                : createLayerChoice;
            model.AddChoice(
                "BranchLayer",
                "02 Presentation",
                "Branch-name layer",
                branchLayerDefault,
                "Select an existing drawing layer, or choose Create new CE Tools layer and type the new layer name below.",
                branchLayerChoices);
            model.AddText(
                "NewBranchLayer",
                "02 Presentation",
                "New CE Tools layer name",
                productionSettings.BranchLabelLayer,
                "Used only when Create new CE Tools layer is selected. The layer is created automatically.");
            model.AddPaperHeight(
                "Height",
                "02 Presentation",
                "Branch-name paper height",
                productionSettings.LabelHeight,
                "Annotative paper height for the green Branch-x names.");
            model.AddPositiveDouble(
                "AboveOffset",
                "02 Presentation",
                "Above offset (paper mm)",
                productionSettings.BranchLabelAboveOffset,
                "Perpendicular paper distance from the sewer centreline when the name is placed above.");
            model.AddPositiveDouble(
                "BelowOffset",
                "02 Presentation",
                "Below offset (paper mm)",
                productionSettings.BranchLabelBelowOffset,
                "Perpendicular paper distance from the sewer centreline when the name is placed below.");
