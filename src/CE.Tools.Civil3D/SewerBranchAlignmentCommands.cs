        {
            return new ResultBuffer(
                new TypedValue(
                    (int)DxfCode.ExtendedDataRegAppName,
                    RegAppName),
                new TypedValue(
                    (int)DxfCode.ExtendedDataAsciiString,
                    branchKey),
                new TypedValue(
                    (int)DxfCode.ExtendedDataAsciiString,
                    objectType));
        }

